def name_to_pid(nm, team):
    for pid in team_players[team]:
        if name_of(pid) == nm:
            return pid
    raise ValueError(f"{nm} not found on {team}")

def marginal_value(pid, roster_pids, weekly_data=None):
    """Points lost if this player were removed from the roster (starter marginal value)."""
    full = optimal_lineup_points(roster_pids, weekly_data)
    without = optimal_lineup_points([p for p in roster_pids if p != pid], weekly_data)
    return full - without
